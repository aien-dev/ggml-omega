static int32_t gb_op_i32(const struct ggml_tensor *t, uint32_t i) { int32_t v; memcpy(&v, (const char *) t->op_params + 4 * i, 4); return v; }

// Omega units (generated by omega-bridge src/native.om, see build.sh)
uint32_t omega_gbmm(uint64_t *r, const void *d, uint64_t d_n, uint64_t g, void *p, uint64_t p_n);
uint32_t omega_dq8r(uint64_t *r, const void *w, uint64_t w_n, void *y, uint64_t y_n);
uint32_t omega_h2fv_32(uint64_t *r, const void *s, uint64_t s_n, void *d, uint64_t d_n);
uint32_t omega_bfs_256(uint64_t *r, const void *s, uint64_t s_n, void *h, uint64_t h_n, void *l, uint64_t l_n);
uint32_t omega_bin_32(uint64_t *r, uint64_t op, const void *a, uint64_t a_n, const void *b, uint64_t b_n, void *d, uint64_t d_n);
uint32_t omega_bin_1(uint64_t *r, uint64_t op, const void *a, uint64_t a_n, const void *b, uint64_t b_n, void *d, uint64_t d_n);

#define OK(call)                                                                       \
    do {                                                                               \
        uint32_t st_ = (call);                                                         \
        if (st_ != 0) GGML_ABORT("ggml-omega-gb10: %s returned Omega status %u", #call, st_); \
    } while (0)

static bool f32t(const struct ggml_tensor *t) { return t && t->type == GGML_TYPE_F32; }
static bool dense_rows(const struct ggml_tensor *t) { return t->nb[0] == ggml_type_size(t->type); }

// --- MUL_MAT ---------------------------------------------------------------------------------------

// src0 as the gemm sees it: its own bytes (f32, f16, bf16) or a dense f32 copy of a q8_0 tensor.
struct w_view { const char *data; size_t nb[4]; uint64_t es; OmegaGemmDtype dt; };

static void w_desc(const struct ggml_tensor *w, struct w_view *v) {
    if (w->type == GGML_TYPE_Q8_0) {
        v->es = 4; v->dt = OMEGA_GEMM_DT_F32;
        v->nb[0] = 4; v->nb[1] = 4 * w->ne[0]; v->nb[2] = v->nb[1] * w->ne[1]; v->nb[3] = v->nb[2] * w->ne[2];
    } else {
        v->es = ggml_type_size(w->type);
        v->dt = w->type == GGML_TYPE_F32 ? OMEGA_GEMM_DT_F32 : w->type == GGML_TYPE_F16 ? OMEGA_GEMM_DT_F16 : OMEGA_GEMM_DT_BF16;
        for (int i = 0; i < 4; i++) v->nb[i] = w->nb[i];
    }
    v->data = w->data;
}

static void mm_desc(const struct ggml_tensor *dst, const struct w_view *v, uint64_t d[32]) {
    const struct ggml_tensor *w = dst->src[0], *x = dst->src[1];
    memset(d, 0, 32 * sizeof *d);
    for (int i = 0; i < 4; i++) {
        d[i] = w->ne[i]; d[4 + i] = v->nb[i];
        d[9 + i] = x->ne[i]; d[13 + i] = x->nb[i];
        d[18 + i] = dst->ne[i]; d[22 + i] = dst->nb[i];
    }
    d[8] = v->es; d[17] = ggml_type_size(x->type); d[26] = ggml_type_size(dst->type);
}

static bool gv_supported(const struct ggml_tensor *op);

static bool mm_supported(const struct ggml_tensor *op) {
    const struct ggml_tensor *w = op->src[0], *x = op->src[1];
    if (!f32t(op) || !f32t(x)) return false;
    if (w->type != GGML_TYPE_F32 && w->type != GGML_TYPE_F16 && w->type != GGML_TYPE_BF16 && w->type != GGML_TYPE_Q8_0) return false;
    if (w->type == GGML_TYPE_Q8_0 && (!dense_rows(w) || w->ne[0] % 32 != 0)) return false;
    if (gb_op_i32(op, 1) == GGML_HINT_SRC0_IS_HADAMARD) return false;
    if (gv_supported(op)) return true;
    struct w_view v; w_desc(w, &v);
    uint64_t d[32], p[16], r = 1;
    mm_desc(op, &v, d);
    OK(omega_gbmm(&r, d, 32, 0, p, 16));
    return r == 0;
}

// --- MUL_MAT, GEMV route: 2-D weights as resident bf16 planes, f32 x, fp32 FFMA accumulation on the chip ---
// A weight W (k a multiple of 256, 256 <= k <= 16384) is held on the chip as bf16 planes: bf16 weights as
// themselves (one plane, exact); f32, f16 and q8_0 (dequantised to f32 by the Omega unit dq8r, exact for q8_0)
// split by the Omega unit bfs into hi + lo, W - (hi + lo) < 2^-16 |W| per element. Each token row is one
// omega_gpu_bf16_gemv_f32 per plane (bf16 widened to f32 times f32 x, fp32 FFMA, CUDApp
// omega_blackwell_codegen_bf16.h); the two plane results are summed by the Omega unit bin (op 0).
// Planes are uploaded once for buffers llama.cpp marks as weights; any other buffer per call.
// k is split into nch chunks of kc = k / nch (kc a multiple of 512, at most 8192): the chip kernel stages x in
// 4 * kc bytes of shared memory (launch descriptor limit 32768) and needs kc % (32 * warps) == 0. The chunk
// results are summed with the Omega unit bin (op 0).
enum { GW_MAXCH = 8 };
struct gw { const void *key; size_t bytes; int planes; int nch; uint32_t kc; OmegaGpuBf16Tensor *t[2][GW_MAXCH]; struct gw *next; };

static int gv_chunks(int64_t k) {
    if (k < 512 || k % 512) return 0;
    for (int c = 1; c <= GW_MAXCH; c++) if (k % c == 0 && (k / c) % 512 == 0 && k / c <= 8192) return c;
    return 0;
}
static struct gw *gw_head;
static pthread_mutex_t gw_mu = PTHREAD_MUTEX_INITIALIZER;

static bool gv_supported(const struct ggml_tensor *op) {
    const struct ggml_tensor *w = op->src[0], *x = op->src[1];
    if (!f32t(op) || !f32t(x) || !dense_rows(x) || !dense_rows(op)) return false;
    if (w->type != GGML_TYPE_F32 && w->type != GGML_TYPE_F16 && w->type != GGML_TYPE_BF16 && w->type != GGML_TYPE_Q8_0) return false;
    if (w->ne[2] != 1 || w->ne[3] != 1 || !ggml_is_contiguous(w)) return false;
    if (gv_chunks(w->ne[0]) == 0 || w->ne[1] > UINT32_MAX) return false;
    if (gb_op_i32(op, 1) == GGML_HINT_SRC0_IS_HADAMARD) return false;
    return x->ne[0] == w->ne[0] && op->ne[0] == w->ne[1];
}

struct split_job { const struct ggml_tensor *w; uint16_t *h, *l; int64_t r0, r1; };

static void *split_rows(void *arg) {
    const struct split_job *j = arg;
    const struct ggml_tensor *w = j->w;
    const int64_t k = w->ne[0];
    float *f = malloc((size_t) k * sizeof *f);
    if (!f) GGML_ABORT("ggml-omega-gb10: out of host memory");
    uint64_t r;
    for (int64_t row = j->r0; row < j->r1; row++) {
        const char *s = (const char *) w->data + row * w->nb[1];
        if (w->type == GGML_TYPE_Q8_0) for (int64_t b = 0; b < k / 32; b++) OK(omega_dq8r(&r, s + 34 * b, 34, f + 32 * b, 32));
        else if (w->type == GGML_TYPE_F16) for (int64_t i = 0; i < k; i += 32) OK(omega_h2fv_32(&r, s + 2 * i, 32, f + i, 32));
        else memcpy(f, s, (size_t) k * sizeof *f);
        for (int64_t i = 0; i < k; i += 256) OK(omega_bfs_256(&r, f + i, 256, j->h + row * k + i, 256, j->l + row * k + i, 256));
    }
    free(f);
    return NULL;
}

static void gw_free(struct gw *g) {
    for (int p = 0; p < 2; p++) for (int c = 0; c < GW_MAXCH; c++) if (g->t[p][c]) omega_gpu_bf16_tensor_free(g->t[p][c]);
}

// Upload one plane (n x k bf16, row-major) as nch chunks of kc columns; false: the chip refused one.
static bool up_plane(uint32_t n, uint32_t k, int nch, const uint16_t *src, OmegaGpuBf16Tensor **out) {
    const uint32_t kc = k / nch;
    if (nch == 1) return omega_gpu_bf16_tensor_upload(n, k, src, &out[0]) == 0;
    uint16_t *tmp = malloc((size_t) n * kc * 2);
    if (!tmp) GGML_ABORT("ggml-omega-gb10: out of host memory");
    bool ok = true;
    for (int c = 0; c < nch && ok; c++) {
        for (uint32_t r = 0; r < n; r++) memcpy(tmp + (size_t) r * kc, src + (size_t) r * k + (size_t) c * kc, (size_t) kc * 2);
        ok = omega_gpu_bf16_tensor_upload(n, kc, tmp, &out[c]) == 0;
    }
    free(tmp);
    return ok;
}

// Upload W's planes; false when the chip refuses a plane (a NaN/Inf weight): the caller takes the gemm route.
static bool gw_upload(const struct ggml_tensor *w, struct gw *g) {
    const uint32_t k = (uint32_t) w->ne[0], n = (uint32_t) w->ne[1];
    memset(g->t, 0, sizeof g->t);
    g->key = w->data; g->bytes = ggml_nbytes(w);
    g->nch = gv_chunks(k); g->kc = k / g->nch;
    if (w->type == GGML_TYPE_BF16) {
        g->planes = 1;
        const bool ok = up_plane(n, k, g->nch, (const uint16_t *) w->data, g->t[0]);
        if (!ok) gw_free(g);
        return ok;
    }
    g->planes = 2;
    uint16_t *h = malloc((size_t) n * k * 2), *l = malloc((size_t) n * k * 2);
    if (!h || !l) GGML_ABORT("ggml-omega-gb10: out of host memory");
    enum { NT = 10 };
    pthread_t th[NT]; struct split_job jb[NT];
    for (int i = 0; i < NT; i++) {
        jb[i] = (struct split_job) { w, h, l, (int64_t) n * i / NT, (int64_t) n * (i + 1) / NT };
        if (pthread_create(&th[i], NULL, split_rows, &jb[i]) != 0) GGML_ABORT("ggml-omega-gb10: pthread_create");
    }
    for (int i = 0; i < NT; i++) pthread_join(th[i], NULL);
    bool ok = up_plane(n, k, g->nch, h, g->t[0]) && up_plane(n, k, g->nch, l, g->t[1]);
    free(h); free(l);
    if (!ok) gw_free(g);
    return ok;
}

// The resident planes of W, or NULL (refused upload). *owned: per-call planes the caller frees.
static struct gw *gw_get(const struct ggml_tensor *w, bool *owned) {
    const bool cache = w->buffer && w->buffer->usage == GGML_BACKEND_BUFFER_USAGE_WEIGHTS;
    *owned = !cache;
    if (cache) {
        pthread_mutex_lock(&gw_mu);
        for (struct gw *c = gw_head; c; c = c->next)
            if (c->key == w->data && c->bytes == ggml_nbytes(w)) { pthread_mutex_unlock(&gw_mu); return c->planes ? c : NULL; }
    }
    struct gw *g = malloc(sizeof *g);
    if (!g) GGML_ABORT("ggml-omega-gb10: out of host memory");
    if (!gw_upload(w, g)) g->planes = 0;
    if (cache) { g->next = gw_head; gw_head = g; pthread_mutex_unlock(&gw_mu); }
    if (g->planes) return g;
    if (!cache) free(g);
    return NULL;
}

static void gemv(const OmegaGpuBf16Tensor *t, const float *x, float *y) {
    const int rc = omega_gpu_bf16_gemv_f32(t, x, y, NULL);
    if (rc != 0) GGML_ABORT("ggml-omega-gb10: omega_gpu_bf16_gemv_f32 %s (%d): %s", omega_gpu_bf16_rc_name(rc), rc, omega_gpu_bf16_last_error());
}

// y = sum over plane and chunk of gemv(t[plane][chunk], x chunk), summed left to right by the Omega unit bin.
static void gv_row(const struct gw *g, const float *xr, float *yr, int64_t n, float *buf[3]) {
    const int parts = g->planes * g->nch;
    if (parts == 1) { gemv(g->t[0][0], xr, yr); return; }
    float *acc = buf[0], *nxt = buf[1], *part = buf[2];
    uint64_t r;
    for (int j = 0; j < parts; j++) {
        const int p = j / g->nch, c = j % g->nch;
        float *out = j == 0 ? acc : part;
        gemv(g->t[p][c], xr + (size_t) c * g->kc, out);
        if (j == 0) continue;
        float *dst = j == parts - 1 ? yr : nxt;
        int64_t i = 0;
        for (; i + 32 <= n; i += 32) OK(omega_bin_32(&r, 0, acc + i, 32, part + i, 32, dst + i, 32));
        for (; i < n; i++) OK(omega_bin_1(&r, 0, acc + i, 1, part + i, 1, dst + i, 1));
        float *t = acc; acc = nxt; nxt = t;
    }
}

// false: the planes were refused, run the gemm route instead.
static bool op_mul_mat_gv(struct ggml_tensor *dst) {
    const struct ggml_tensor *w = dst->src[0], *x = dst->src[1];
    bool owned;
    struct gw *g = gw_get(w, &owned);
    if (!g) return false;
    const int64_t n = w->ne[1];
    float *buf[3] = { NULL, NULL, NULL };
    if (g->planes * g->nch > 1)
        for (int i = 0; i < 3; i++) if (!(buf[i] = malloc((size_t) n * sizeof(float)))) GGML_ABORT("ggml-omega-gb10: out of host memory");
    for (int64_t i3 = 0; i3 < x->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < x->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < x->ne[1]; i1++) {
                const float *xr = (const float *) ((const char *) x->data + i1 * x->nb[1] + i2 * x->nb[2] + i3 * x->nb[3]);
                float *yr = (float *) ((char *) dst->data + i1 * dst->nb[1] + i2 * dst->nb[2] + i3 * dst->nb[3]);
                gv_row(g, xr, yr, n, buf);
            }
    for (int i = 0; i < 3; i++) free(buf[i]);
    if (owned) { gw_free(g); free(g); }
    return true;
}

// --- MUL_MAT, gemm route (every other accepted shape): src0 per call, q8_0 dequantised per call ---
static float *q8_dequant(const struct ggml_tensor *w) {
    const int64_t rows = w->ne[1] * w->ne[2] * w->ne[3], blocks = w->ne[0] / 32;
    float *f = malloc((size_t) (rows * w->ne[0]) * sizeof *f);
    if (!f) GGML_ABORT("ggml-omega-gb10: out of host memory");
    uint64_t r;
    for (int64_t i3 = 0, row = 0; i3 < w->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < w->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < w->ne[1]; i1++, row++) {
                const char *s = (const char *) w->data + i1 * w->nb[1] + i2 * w->nb[2] + i3 * w->nb[3];
                for (int64_t b = 0; b < blocks; b++) OK(omega_dq8r(&r, s + 34 * b, 34, f + row * w->ne[0] + 32 * b, 32));
            }
    return f;
}

static void op_mul_mat(struct ggml_tensor *dst) {
    if (gv_supported(dst) && op_mul_mat_gv(dst)) return;
    const struct ggml_tensor *w = dst->src[0], *x = dst->src[1];
    struct w_view v; w_desc(w, &v);
    const bool owned = w->type == GGML_TYPE_Q8_0;
    if (owned) v.data = (const char *) q8_dequant(w);
    uint64_t d[32], p[16], r;
    mm_desc(dst, &v, d);
    OK(omega_gbmm(&r, d, 32, 0, p, 16));
    if (r != 0) GGML_ABORT("ggml-omega-gb10: gbmm refused a MUL_MAT it accepted in supports_op (rule %llu)", (unsigned long long) r);
    const uint64_t groups = p[13];
    for (uint64_t g = 0; g < groups; g++) {
        OK(omega_gbmm(&r, d, 32, g, p, 16));
        if (r != 0) GGML_ABORT("ggml-omega-gb10: gbmm rule %llu at call %llu", (unsigned long long) r, (unsigned long long) g);
        OmegaGemmExArgs a = {
            .op_a = OMEGA_GEMM_OP_N, .op_b = OMEGA_GEMM_OP_T,
            .m = p[0], .n = p[1], .k = p[2], .batch = p[6],
            .a_type = OMEGA_GEMM_DT_F32, .b_type = v.dt, .c_type = OMEGA_GEMM_DT_F32,
            .a = (const char *) x->data + p[10], .lda = p[3], .stride_a = p[7],
            .b = v.data + p[11], .ldb = p[4], .stride_b = p[8],
            .c = (char *) dst->data + p[12], .ldc = p[5], .stride_c = p[9],
            .alpha = 1.0f, .beta = 0.0f, .compute = OMEGA_GEMM_EX_DEFAULT, .scale = OMEGA_GEMM_SCALE_NONE,
        };
        const int rc = omega_gpu_gemm_ex(&a);
        if (rc != 0) GGML_ABORT("ggml-omega-gb10: omega_gpu_gemm_ex %s (%d)", omega_gpu_gemm_rc_name(rc), rc);
    }
    if (owned) free((void *) v.data);
}

// --- RMS_NORM and GLU: rows gathered into dense staging buffers, one chip call, rows scattered back ---

static float *stage_alloc(size_t n) {
    float *s = malloc((n ? n : 1) * sizeof *s);
    if (!s) GGML_ABORT("ggml-omega-gb10: out of host memory");
    return s;
}

static void gather(const struct ggml_tensor *t, size_t off, int64_t nc, float *s) {
    for (int64_t i3 = 0, row = 0; i3 < t->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < t->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < t->ne[1]; i1++, row++)
                memcpy(s + row * nc, (const char *) t->data + off + i1 * t->nb[1] + i2 * t->nb[2] + i3 * t->nb[3], nc * 4);
}

static void scatter(struct ggml_tensor *t, const float *s) {
    const int64_t nc = t->ne[0];
    for (int64_t i3 = 0, row = 0; i3 < t->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < t->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < t->ne[1]; i1++, row++)
                memcpy((char *) t->data + i1 * t->nb[1] + i2 * t->nb[2] + i3 * t->nb[3], s + row * nc, nc * 4);
}

static bool rms_supported(const struct ggml_tensor *op) {
    const struct ggml_tensor *s0 = op->src[0];
    return f32t(op) && f32t(s0) && dense_rows(op) && dense_rows(s0) && ggml_are_same_shape(op, s0) &&
           s0->ne[0] % 128 == 0 && s0->ne[0] <= 16384 && ggml_nrows(s0) <= UINT32_MAX;
}

static void op_rms_norm(struct ggml_tensor *dst) {
    const struct ggml_tensor *s0 = dst->src[0];
    const int64_t dim = s0->ne[0], rows = ggml_nrows(s0);
    float eps; memcpy(&eps, dst->op_params, sizeof eps);
    float *x = stage_alloc((size_t) (rows * dim)), *y = stage_alloc((size_t) (rows * dim)), *one = stage_alloc((size_t) dim);
    for (int64_t i = 0; i < dim; i++) one[i] = 1.0f;
    gather(s0, 0, dim, x);
    const int rc = omega_gpu_rmsnorm_f32((uint32_t) rows, (uint32_t) dim, x, one, eps, y, NULL);
    if (rc != 0) GGML_ABORT("ggml-omega-gb10: omega_gpu_rmsnorm_f32 %s (%d)", omega_gpu_elementwise_rc_name(rc), rc);
    scatter(dst, y);
    free(x); free(y); free(one);
}

static bool glu_supported(const struct ggml_tensor *op) {
    const struct ggml_tensor *s0 = op->src[0], *s1 = op->src[1];
    return ggml_get_glu_op(op) == GGML_GLU_OP_SWIGLU && f32t(op) && f32t(s0) && (!s1 || f32t(s1)) &&
           dense_rows(op) && dense_rows(s0) && (!s1 || dense_rows(s1)) &&
           (uint64_t) ggml_nelements(op) <= UINT32_MAX;
}

static void op_swiglu(struct ggml_tensor *dst) {
    const struct ggml_tensor *s0 = dst->src[0], *s1 = dst->src[1];
    const int64_t nc = dst->ne[0], n = ggml_nelements(dst);
    const int swapped = gb_op_i32(dst, 1);
    float *ga = stage_alloc((size_t) n), *up = stage_alloc((size_t) n), *y = stage_alloc((size_t) n);
    if (s1) { gather(s0, 0, nc, ga); gather(s1, 0, nc, up); }
    else { gather(s0, swapped ? 4 * nc : 0, nc, ga); gather(s0, swapped ? 0 : 4 * nc, nc, up); }
    const int rc = omega_gpu_swiglu_f32((uint32_t) n, ga, up, y, NULL);
    if (rc != 0) GGML_ABORT("ggml-omega-gb10: omega_gpu_swiglu_f32 %s (%d)", omega_gpu_elementwise_rc_name(rc), rc);
    scatter(dst, y);
    free(ga); free(up); free(y);
}

// --- device and backend --------------------------------------------------------------------------------

bool omega_gb10_supports_op(const struct ggml_tensor *op) {
    switch (op->op) {
        case GGML_OP_NONE: case GGML_OP_RESHAPE: case GGML_OP_VIEW: case GGML_OP_PERMUTE: case GGML_OP_TRANSPOSE:
            return true;
        case GGML_OP_MUL_MAT: return mm_supported(op);
        case GGML_OP_RMS_NORM: return rms_supported(op);
        case GGML_OP_GLU: return glu_supported(op);
        default: return false;
    }
}

static const char *gb10_name(ggml_backend_t b) { (void) b; return OMEGA_GB10_NAME; }
static void gb10_free(ggml_backend_t b) { free(b); }

// OMEGA_GGML_PROFILE=1: wall time per op (ggml_op_desc) inside this device's graph_compute, printed to stderr
// at exit. Host clock around each synchronous chip call; for op placement and decode shares, not a receipt.
enum { PROF_MAX = 32 };
static struct { const char *op; uint64_t calls, ns; } prof[PROF_MAX];
static int prof_on = -1;
static uint64_t now_ns(void) { struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return (uint64_t) t.tv_sec * 1000000000u + (uint64_t) t.tv_nsec; }
static void prof_dump(void) {
    for (int i = 0; i < PROF_MAX && prof[i].op; i++)
        fprintf(stderr, "omega-gb10-profile op=%s calls=%llu ms=%.3f\n", prof[i].op, (unsigned long long) prof[i].calls, prof[i].ns / 1e6);
}
static void prof_add(const char *op, uint64_t ns) {
    for (int i = 0; i < PROF_MAX; i++) {
        if (!prof[i].op) prof[i].op = op;
        if (strcmp(prof[i].op, op) == 0) { prof[i].calls++; prof[i].ns += ns; return; }
    }
}

static enum ggml_status gb10_graph_compute(ggml_backend_t backend, struct ggml_cgraph *g) {
    (void) backend;
    if (prof_on < 0) { const char *e = getenv("OMEGA_GGML_PROFILE"); prof_on = e && *e == '1'; if (prof_on) atexit(prof_dump); }
    for (int i = 0; i < ggml_graph_n_nodes(g); i++) {
        struct ggml_tensor *n = ggml_graph_node(g, i);
        if ((n->flags & GGML_TENSOR_FLAG_COMPUTE) == 0) continue;
        const uint64_t t0 = prof_on ? now_ns() : 0;
        switch (n->op) {
            case GGML_OP_NONE: case GGML_OP_RESHAPE: case GGML_OP_VIEW: case GGML_OP_PERMUTE: case GGML_OP_TRANSPOSE: continue;
            case GGML_OP_MUL_MAT: op_mul_mat(n); break;
            case GGML_OP_RMS_NORM: op_rms_norm(n); break;
            case GGML_OP_GLU: op_swiglu(n); break;
            default: GGML_ABORT("ggml-omega-gb10: op %s reached graph_compute without support", ggml_op_name(n->op));
        }
        if (prof_on) prof_add(ggml_op_desc(n), now_ns() - t0);
    }
    return GGML_STATUS_SUCCESS;
}

static const struct ggml_backend_i gb10_backend_i = {
    .get_name = gb10_name,
    .free = gb10_free,
    .graph_compute = gb10_graph_compute,
};

static ggml_guid_t gb10_guid(void) {
    static ggml_guid guid = { 0x4f, 0x6d, 0x65, 0x67, 0x61, 0x2d, 0x47, 0x42, 0x31, 0x30, 0x2d, 0x63, 0x75, 0x64, 0x61, 0x70 };
    return &guid;
}

ggml_backend_t omega_gb10_init(ggml_backend_dev_t d) {
    ggml_backend_t b = malloc(sizeof *b);
    if (!b) return NULL;
    *b = (struct ggml_backend) { .guid = gb10_guid(), .iface = gb10_backend_i, .device = d, .context = NULL };
    return b;
}
