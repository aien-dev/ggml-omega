// ggml-omega-gb10.c: the "OmegaGB10" device of ggml-omega. MUL_MAT, RMS_NORM and GLU (swiglu) run on the
// NVIDIA GB10 through CUDA++ (aien-dev/CUDApp) runtime calls whose kernels come from Omega's own code
// generator (no CUDA toolkit, no NVIDIA user-space library). Every other op stays on ggml's CPU backend.
//
// INTERIM HOST GLUE, migration-pending C (build switch OMEGA_GGML_GB10=1 in build.sh, off by default).
// This file only fills tensor descriptors, stages rows into dense buffers and back (bit moves) and calls
// the CUDApp entries. The MUL_MAT shape rules, leading dimensions, batch strides and per-call byte
// offsets are computed by the seeded-Omega unit kernels/gbmm.om; q8_0 weights are dequantised by the
// Omega unit kernels/dq8r.om. Named .om successor: the same unit set exported as an Omega loadable
// object (aien-dev/omega-mv #636/#637) calling the CUDApp entries, once Omega has host callbacks.
//
// Arithmetic on the chip (CUDApp src/omega_gpu_gemm_ex.h, src/omega_gpu_elementwise_api.h):
//   MUL_MAT   omega_gpu_gemm_ex, A = src1 (f32), B = src0 op T (f32, f16 or bf16; q8_0 dequantised to f32),
//             the f32 route is bf16x3 on HMMA.BF16 with fp32 tensor-core accumulation: not exact fp32.
//   RMS_NORM  omega_gpu_rmsnorm_f32 with weight 1 (dim a multiple of 128, at most 16384).
//   GLU       omega_gpu_swiglu_f32 (MUFU.EX2 / MUFU.RCP: approximate units).
// Same device model as the host device: ACCEL with the CPU buffer type, so weights stay in CPU buffers.

#include "ggml-backend-impl.h"
#include "ggml.h"
#include "ggml-omega-gb10.h"

#include "omega_gpu_elementwise_api.h"
#include "omega_gpu_gemm_ex.h"

#include <pthread.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

static int32_t gb_op_i32(const struct ggml_tensor *t, uint32_t i) { int32_t v; memcpy(&v, (const char *) t->op_params + 4 * i, 4); return v; }

// Omega units (generated by omega-bridge src/native.om, see build.sh)
uint32_t omega_gbmm(uint64_t *r, const void *d, uint64_t d_n, uint64_t g, void *p, uint64_t p_n);
uint32_t omega_dq8r(uint64_t *r, const void *w, uint64_t w_n, void *y, uint64_t y_n);

#define OK(call)                                                                       \
    do {                                                                               \
        uint32_t st_ = (call);                                                         \
        if (st_ != 0) GGML_ABORT("ggml-omega-gb10: %s returned Omega status %u", #call, st_); \
    } while (0)

static bool f32t(const struct ggml_tensor *t) { return t && t->type == GGML_TYPE_F32; }
static bool dense_rows(const struct ggml_tensor *t) { return t->nb[0] == ggml_type_size(t->type); }

// --- MUL_MAT ---------------------------------------------------------------------------------------

// src0 as the gemm sees it: its own bytes (f32, f16, bf16) or a dense f32 copy of a q8_0 tensor.
struct w_view { const char *data; size_t nb[4]; uint64_t es; OmegaGemmDtype dt; };

static void w_desc(const struct ggml_tensor *w, struct w_view *v) {
    if (w->type == GGML_TYPE_Q8_0) {
        v->es = 4; v->dt = OMEGA_GEMM_DT_F32;
        v->nb[0] = 4; v->nb[1] = 4 * w->ne[0]; v->nb[2] = v->nb[1] * w->ne[1]; v->nb[3] = v->nb[2] * w->ne[2];
    } else {
        v->es = ggml_type_size(w->type);
        v->dt = w->type == GGML_TYPE_F32 ? OMEGA_GEMM_DT_F32 : w->type == GGML_TYPE_F16 ? OMEGA_GEMM_DT_F16 : OMEGA_GEMM_DT_BF16;
        for (int i = 0; i < 4; i++) v->nb[i] = w->nb[i];
    }
    v->data = w->data;
}

static void mm_desc(const struct ggml_tensor *dst, const struct w_view *v, uint64_t d[32]) {
    const struct ggml_tensor *w = dst->src[0], *x = dst->src[1];
    memset(d, 0, 32 * sizeof *d);
    for (int i = 0; i < 4; i++) {
        d[i] = w->ne[i]; d[4 + i] = v->nb[i];
        d[9 + i] = x->ne[i]; d[13 + i] = x->nb[i];
        d[18 + i] = dst->ne[i]; d[22 + i] = dst->nb[i];
    }
    d[8] = v->es; d[17] = ggml_type_size(x->type); d[26] = ggml_type_size(dst->type);
}

static bool mm_supported(const struct ggml_tensor *op) {
    const struct ggml_tensor *w = op->src[0], *x = op->src[1];
    if (!f32t(op) || !f32t(x)) return false;
    if (w->type != GGML_TYPE_F32 && w->type != GGML_TYPE_F16 && w->type != GGML_TYPE_BF16 && w->type != GGML_TYPE_Q8_0) return false;
    if (w->type == GGML_TYPE_Q8_0 && (!dense_rows(w) || w->ne[0] % 32 != 0)) return false;
    if (gb_op_i32(op, 1) == GGML_HINT_SRC0_IS_HADAMARD) return false;
    struct w_view v; w_desc(w, &v);
    uint64_t d[32], p[16], r = 1;
    mm_desc(op, &v, d);
    OK(omega_gbmm(&r, d, 32, 0, p, 16));
    return r == 0;
}

// Dequantised q8_0 weights, kept for buffers llama.cpp marks as weights (their bytes never change);
// any other buffer is dequantised per call (test-backend-ops reuses addresses with new contents).
struct q8_cache { const void *key; size_t bytes; float *f; struct q8_cache *next; };
static struct q8_cache *q8_head;
static pthread_mutex_t q8_mu = PTHREAD_MUTEX_INITIALIZER;

static float *q8_dequant(const struct ggml_tensor *w) {
    const int64_t rows = w->ne[1] * w->ne[2] * w->ne[3], blocks = w->ne[0] / 32;
    float *f = malloc((size_t) (rows * w->ne[0]) * sizeof *f);
    if (!f) GGML_ABORT("ggml-omega-gb10: out of host memory");
    uint64_t r;
    for (int64_t i3 = 0, row = 0; i3 < w->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < w->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < w->ne[1]; i1++, row++) {
                const char *s = (const char *) w->data + i1 * w->nb[1] + i2 * w->nb[2] + i3 * w->nb[3];
                for (int64_t b = 0; b < blocks; b++) OK(omega_dq8r(&r, s + 34 * b, 34, f + row * w->ne[0] + 32 * b, 32));
            }
    return f;
}

static const float *q8_weights(const struct ggml_tensor *w, bool *owned) {
    const bool cache = w->buffer && w->buffer->usage == GGML_BACKEND_BUFFER_USAGE_WEIGHTS;
    *owned = !cache;
    if (!cache) return q8_dequant(w);
    pthread_mutex_lock(&q8_mu);
    for (struct q8_cache *c = q8_head; c; c = c->next)
        if (c->key == w->data && c->bytes == ggml_nbytes(w)) { pthread_mutex_unlock(&q8_mu); return c->f; }
    struct q8_cache *c = malloc(sizeof *c);
    if (!c) GGML_ABORT("ggml-omega-gb10: out of host memory");
    *c = (struct q8_cache) { w->data, ggml_nbytes(w), q8_dequant(w), q8_head };
    q8_head = c;
    pthread_mutex_unlock(&q8_mu);
    return c->f;
}

static void op_mul_mat(struct ggml_tensor *dst) {
    const struct ggml_tensor *w = dst->src[0], *x = dst->src[1];
    struct w_view v; w_desc(w, &v);
    bool owned = false;
    if (w->type == GGML_TYPE_Q8_0) v.data = (const char *) q8_weights(w, &owned);
    uint64_t d[32], p[16], r;
    mm_desc(dst, &v, d);
    OK(omega_gbmm(&r, d, 32, 0, p, 16));
    if (r != 0) GGML_ABORT("ggml-omega-gb10: gbmm refused a MUL_MAT it accepted in supports_op (rule %llu)", (unsigned long long) r);
    const uint64_t groups = p[13];
    for (uint64_t g = 0; g < groups; g++) {
        OK(omega_gbmm(&r, d, 32, g, p, 16));
        if (r != 0) GGML_ABORT("ggml-omega-gb10: gbmm rule %llu at call %llu", (unsigned long long) r, (unsigned long long) g);
        OmegaGemmExArgs a = {
            .op_a = OMEGA_GEMM_OP_N, .op_b = OMEGA_GEMM_OP_T,
            .m = p[0], .n = p[1], .k = p[2], .batch = p[6],
            .a_type = OMEGA_GEMM_DT_F32, .b_type = v.dt, .c_type = OMEGA_GEMM_DT_F32,
            .a = (const char *) x->data + p[10], .lda = p[3], .stride_a = p[7],
            .b = v.data + p[11], .ldb = p[4], .stride_b = p[8],
            .c = (char *) dst->data + p[12], .ldc = p[5], .stride_c = p[9],
            .alpha = 1.0f, .beta = 0.0f, .compute = OMEGA_GEMM_EX_DEFAULT, .scale = OMEGA_GEMM_SCALE_NONE,
        };
        const int rc = omega_gpu_gemm_ex(&a);
        if (rc != 0) GGML_ABORT("ggml-omega-gb10: omega_gpu_gemm_ex %s (%d)", omega_gpu_gemm_rc_name(rc), rc);
    }
    if (owned) free((void *) v.data);
}

// --- RMS_NORM and GLU: rows gathered into dense staging buffers, one chip call, rows scattered back ---

static float *stage_alloc(size_t n) {
    float *s = malloc((n ? n : 1) * sizeof *s);
    if (!s) GGML_ABORT("ggml-omega-gb10: out of host memory");
    return s;
}

static void gather(const struct ggml_tensor *t, size_t off, int64_t nc, float *s) {
    for (int64_t i3 = 0, row = 0; i3 < t->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < t->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < t->ne[1]; i1++, row++)
                memcpy(s + row * nc, (const char *) t->data + off + i1 * t->nb[1] + i2 * t->nb[2] + i3 * t->nb[3], nc * 4);
}

static void scatter(struct ggml_tensor *t, const float *s) {
    const int64_t nc = t->ne[0];
    for (int64_t i3 = 0, row = 0; i3 < t->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < t->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < t->ne[1]; i1++, row++)
                memcpy((char *) t->data + i1 * t->nb[1] + i2 * t->nb[2] + i3 * t->nb[3], s + row * nc, nc * 4);
}

static bool rms_supported(const struct ggml_tensor *op) {
    const struct ggml_tensor *s0 = op->src[0];
    return f32t(op) && f32t(s0) && dense_rows(op) && dense_rows(s0) && ggml_are_same_shape(op, s0) &&
           s0->ne[0] % 128 == 0 && s0->ne[0] <= 16384 && ggml_nrows(s0) <= UINT32_MAX;
}

static void op_rms_norm(struct ggml_tensor *dst) {
    const struct ggml_tensor *s0 = dst->src[0];
    const int64_t dim = s0->ne[0], rows = ggml_nrows(s0);
    float eps; memcpy(&eps, dst->op_params, sizeof eps);
    float *x = stage_alloc((size_t) (rows * dim)), *y = stage_alloc((size_t) (rows * dim)), *one = stage_alloc((size_t) dim);
    for (int64_t i = 0; i < dim; i++) one[i] = 1.0f;
    gather(s0, 0, dim, x);
    const int rc = omega_gpu_rmsnorm_f32((uint32_t) rows, (uint32_t) dim, x, one, eps, y, NULL);
    if (rc != 0) GGML_ABORT("ggml-omega-gb10: omega_gpu_rmsnorm_f32 %s (%d)", omega_gpu_elementwise_rc_name(rc), rc);
    scatter(dst, y);
    free(x); free(y); free(one);
}

static bool glu_supported(const struct ggml_tensor *op) {
    const struct ggml_tensor *s0 = op->src[0], *s1 = op->src[1];
    return ggml_get_glu_op(op) == GGML_GLU_OP_SWIGLU && f32t(op) && f32t(s0) && (!s1 || f32t(s1)) &&
           dense_rows(op) && dense_rows(s0) && (!s1 || dense_rows(s1)) &&
           (uint64_t) ggml_nelements(op) <= UINT32_MAX;
}

static void op_swiglu(struct ggml_tensor *dst) {
    const struct ggml_tensor *s0 = dst->src[0], *s1 = dst->src[1];
    const int64_t nc = dst->ne[0], n = ggml_nelements(dst);
    const int swapped = gb_op_i32(dst, 1);
    float *ga = stage_alloc((size_t) n), *up = stage_alloc((size_t) n), *y = stage_alloc((size_t) n);
    if (s1) { gather(s0, 0, nc, ga); gather(s1, 0, nc, up); }
    else { gather(s0, swapped ? 4 * nc : 0, nc, ga); gather(s0, swapped ? 0 : 4 * nc, nc, up); }
    const int rc = omega_gpu_swiglu_f32((uint32_t) n, ga, up, y, NULL);
    if (rc != 0) GGML_ABORT("ggml-omega-gb10: omega_gpu_swiglu_f32 %s (%d)", omega_gpu_elementwise_rc_name(rc), rc);
    scatter(dst, y);
    free(ga); free(up); free(y);
}

// --- device and backend --------------------------------------------------------------------------------

bool omega_gb10_supports_op(const struct ggml_tensor *op) {
    switch (op->op) {
        case GGML_OP_NONE: case GGML_OP_RESHAPE: case GGML_OP_VIEW: case GGML_OP_PERMUTE: case GGML_OP_TRANSPOSE:
            return true;
        case GGML_OP_MUL_MAT: return mm_supported(op);
        case GGML_OP_RMS_NORM: return rms_supported(op);
        case GGML_OP_GLU: return glu_supported(op);
        default: return false;
    }
}

static const char *gb10_name(ggml_backend_t b) { (void) b; return OMEGA_GB10_NAME; }
static void gb10_free(ggml_backend_t b) { free(b); }

static enum ggml_status gb10_graph_compute(ggml_backend_t backend, struct ggml_cgraph *g) {
    (void) backend;
    for (int i = 0; i < ggml_graph_n_nodes(g); i++) {
        struct ggml_tensor *n = ggml_graph_node(g, i);
        if ((n->flags & GGML_TENSOR_FLAG_COMPUTE) == 0) continue;
        switch (n->op) {
            case GGML_OP_NONE: case GGML_OP_RESHAPE: case GGML_OP_VIEW: case GGML_OP_PERMUTE: case GGML_OP_TRANSPOSE: break;
            case GGML_OP_MUL_MAT: op_mul_mat(n); break;
            case GGML_OP_RMS_NORM: op_rms_norm(n); break;
            case GGML_OP_GLU: op_swiglu(n); break;
            default: GGML_ABORT("ggml-omega-gb10: op %s reached graph_compute without support", ggml_op_name(n->op));
        }
    }
    return GGML_STATUS_SUCCESS;
}

static const struct ggml_backend_i gb10_backend_i = {
    .get_name = gb10_name,
    .free = gb10_free,
    .graph_compute = gb10_graph_compute,
};

static ggml_guid_t gb10_guid(void) {
    static ggml_guid guid = { 0x4f, 0x6d, 0x65, 0x67, 0x61, 0x2d, 0x47, 0x42, 0x31, 0x30, 0x2d, 0x63, 0x75, 0x64, 0x61, 0x70 };
    return &guid;
}

ggml_backend_t omega_gb10_init(ggml_backend_dev_t d) {
    ggml_backend_t b = malloc(sizeof *b);
    if (!b) return NULL;
    *b = (struct ggml_backend) { .guid = gb10_guid(), .iface = gb10_backend_i, .device = d, .context = NULL };
    return b;
}
