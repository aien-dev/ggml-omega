struct omega_ctx { int n_threads; };

static const char *omega_name(ggml_backend_t b) { (void) b; return "Omega"; }
static void omega_free(ggml_backend_t b) { free(b->context); free(b); }

static enum ggml_status omega_graph_compute(ggml_backend_t backend, struct ggml_cgraph *g) {
    const struct omega_ctx *ctx = backend->context;
    for (int i = 0; i < ggml_graph_n_nodes(g); i++) {
        struct ggml_tensor *n = ggml_graph_node(g, i);
        if ((n->flags & GGML_TENSOR_FLAG_COMPUTE) == 0) continue;
        switch (n->op) {
            case GGML_OP_NONE: case GGML_OP_RESHAPE: case GGML_OP_VIEW: case GGML_OP_PERMUTE: case GGML_OP_TRANSPOSE: break;
            case GGML_OP_ADD: op_bin(n, 0); break;
            case GGML_OP_SUB: op_bin(n, 1); break;
            case GGML_OP_MUL: op_bin(n, 2); break;
            case GGML_OP_DIV: op_bin(n, 3); break;
            case GGML_OP_RMS_NORM: op_rms_norm(n); break;
            case GGML_OP_SCALE: op_scale(n); break;
            case GGML_OP_SOFT_MAX: op_soft_max(n); break;
            case GGML_OP_ROPE: op_rope(n); break;
            case GGML_OP_GET_ROWS: op_get_rows(n); break;
            case GGML_OP_SET_ROWS: op_set_rows(n); break;
            case GGML_OP_CPY: case GGML_OP_CONT: case GGML_OP_DUP: op_cpy(n); break;
            case GGML_OP_GLU: op_swiglu(n); break;
            case GGML_OP_UNARY: op_silu(n); break;
            case GGML_OP_MUL_MAT: op_mul_mat(n, ctx->n_threads); break;
            default: GGML_ABORT("ggml-omega: op %s reached graph_compute without support", ggml_op_name(n->op));
        }
    }
    return GGML_STATUS_SUCCESS;
}

static const struct ggml_backend_i omega_backend_i = {
    .get_name = omega_name,
    .free = omega_free,
    .graph_compute = omega_graph_compute,
};

static ggml_guid_t omega_guid(void) {
    static ggml_guid guid = { 0x4f, 0x6d, 0x65, 0x67, 0x61, 0x2d, 0x67, 0x67, 0x6d, 0x6c, 0x2d, 0x62, 0x72, 0x69, 0x64, 0x67 };
    return &guid;
}

static void omega_set_n_threads(ggml_backend_t b, int n) {
    GGML_ASSERT(b);
    if (!ggml_guid_matches(b->guid, omega_guid())) return;  // the GB10 backend has no host thread pool
    ((struct omega_ctx *) b->context)->n_threads = n;
}

static ggml_backend_reg_t omega_reg(void);

// Device context: NULL is the host device "Omega"; &gb10_tag is the GB10 device (OMEGA_GGML_GB10 builds).
static int gb10_tag;
static bool is_gb10(ggml_backend_dev_t d) { return d->context == &gb10_tag; }

#ifdef OMEGA_GGML_GB10
#include "ggml-omega-gb10.h"
#endif

static const char *dev_name(ggml_backend_dev_t d) {
#ifdef OMEGA_GGML_GB10
    if (is_gb10(d)) return OMEGA_GB10_NAME;
#endif
    (void) d; return "Omega";
}
static const char *dev_desc(ggml_backend_dev_t d) {
    return is_gb10(d) ? "NVIDIA GB10 via CUDA++ (aien-dev/CUDApp), Omega-planned" : "seeded-Omega kernels via omega-bridge (host)";
}
static void dev_memory(ggml_backend_dev_t d, size_t *free_, size_t *total) { (void) d; *free_ = 0; *total = 0; }
static enum ggml_backend_dev_type dev_type(ggml_backend_dev_t d) { (void) d; return GGML_BACKEND_DEVICE_TYPE_ACCEL; }

static void dev_props(ggml_backend_dev_t d, struct ggml_backend_dev_props *p) {
    p->name = dev_name(d); p->description = dev_desc(d); p->type = dev_type(d); p->device_id = NULL;
    dev_memory(d, &p->memory_free, &p->memory_total);
    p->caps = (struct ggml_backend_dev_caps) { .async = false, .host_buffer = false, .buffer_from_host_ptr = true, .events = false, .mmap_support = true };
}

static ggml_backend_t dev_init(ggml_backend_dev_t d, const char *params) {
    (void) params;
#ifdef OMEGA_GGML_GB10
    if (is_gb10(d)) return omega_gb10_init(d);
#endif
    struct omega_ctx *ctx = malloc(sizeof *ctx);
    ggml_backend_t b = malloc(sizeof *b);
    if (!ctx || !b) { free(ctx); free(b); return NULL; }
    ctx->n_threads = 1;
    *b = (struct ggml_backend) { .guid = omega_guid(), .iface = omega_backend_i, .device = d, .context = ctx };
    return b;
}

static ggml_backend_buffer_type_t dev_buft(ggml_backend_dev_t d) { (void) d; return ggml_backend_cpu_buffer_type(); }
static ggml_backend_buffer_t dev_from_ptr(ggml_backend_dev_t d, void *ptr, size_t size, size_t max) {
    (void) d; (void) max; return ggml_backend_cpu_buffer_from_ptr(ptr, size);
}
static bool dev_supports_buft(ggml_backend_dev_t d, ggml_backend_buffer_type_t b) { (void) d; return ggml_backend_buft_is_host(b); }

static bool f32(const struct ggml_tensor *t) { return t && t->type == GGML_TYPE_F32; }
static bool rows1(const struct ggml_tensor *t) { return t->nb[0] == ggml_type_size(t->type); }  // contiguous within a row
static bool fh(const struct ggml_tensor *t) { return t->type == GGML_TYPE_F32 || t->type == GGML_TYPE_F16; }

static bool dev_supports_op(ggml_backend_dev_t d, const struct ggml_tensor *op) {
#ifdef OMEGA_GGML_GB10
    if (is_gb10(d)) return omega_gb10_supports_op(op);
#endif
    (void) d;
    const struct ggml_tensor *s0 = op->src[0], *s1 = op->src[1];
    switch (op->op) {
        case GGML_OP_NONE: case GGML_OP_RESHAPE: case GGML_OP_VIEW: case GGML_OP_PERMUTE: case GGML_OP_TRANSPOSE:
            return true;
        case GGML_OP_ADD: case GGML_OP_SUB: case GGML_OP_MUL: case GGML_OP_DIV:
            return f32(op) && f32(s0) && f32(s1) && rows1(op) && rows1(s0) && rows1(s1) &&
                   ggml_are_same_shape(op, s0) && s1->ne[0] == s0->ne[0] && ggml_can_repeat(s1, s0);
        case GGML_OP_RMS_NORM: case GGML_OP_SCALE:
            return f32(op) && f32(s0) && rows1(op) && rows1(s0);
        case GGML_OP_SOFT_MAX:
            return f32(op) && f32(s0) && rows1(op) && rows1(s0) && op->src[2] == NULL &&
                   ggml_get_op_params_f32(op, 1) == 0.0f &&
                   (!s1 || ((s1->type == GGML_TYPE_F32 || s1->type == GGML_TYPE_F16) && rows1(s1) && s1->ne[0] == s0->ne[0] &&
                            s1->ne[1] >= s0->ne[1] && s0->ne[2] % s1->ne[2] == 0 && s0->ne[3] % s1->ne[3] == 0));
        case GGML_OP_ROPE: {
            const int mode = ggml_get_op_params_i32(op, 2);
            return f32(op) && f32(s0) && rows1(op) && rows1(s0) && s1->type == GGML_TYPE_I32 && op->src[2] == NULL &&
                   (mode == GGML_ROPE_TYPE_NORMAL || mode == GGML_ROPE_TYPE_NEOX) &&
                   ggml_get_op_params_f32(op, 7) == 0.0f && ggml_get_op_params_i32(op, 1) % 2 == 0;
        }
        case GGML_OP_GET_ROWS:
            return f32(op) && rows1(op) && s1->type == GGML_TYPE_I32 &&
                   (s0->type == GGML_TYPE_F32 || s0->type == GGML_TYPE_F16 || s0->type == GGML_TYPE_Q8_0) && rows1(s0);
        case GGML_OP_SET_ROWS:
            return f32(s0) && fh(op) && rows1(op) && rows1(s0) && (s1->type == GGML_TYPE_I64 || s1->type == GGML_TYPE_I32);
        case GGML_OP_CPY: case GGML_OP_CONT: case GGML_OP_DUP: {
            const struct ggml_tensor *dst = op;
            return fh(s0) && fh(dst) && rows1(s0) && rows1(dst) &&
                   (ggml_are_same_shape(s0, dst) || (ggml_is_contiguous(s0) && ggml_is_contiguous(dst)));
        }
        case GGML_OP_GLU:
            return ggml_get_glu_op(op) == GGML_GLU_OP_SWIGLU && f32(op) && f32(s0) && (!s1 || f32(s1)) &&
                   ggml_is_contiguous_1(s0) && ggml_is_contiguous_1(op) && (!s1 || ggml_is_contiguous_1(s1));
        case GGML_OP_UNARY:
            return ggml_get_unary_op(op) == GGML_UNARY_OP_SILU && f32(op) && f32(s0) && rows1(op) && rows1(s0);
        case GGML_OP_MUL_MAT:
            return f32(op) && f32(s1) && rows1(op) && rows1(s1) && rows1(s0) &&
                   (s0->type == GGML_TYPE_F32 || s0->type == GGML_TYPE_F16 || s0->type == GGML_TYPE_Q8_0) &&
                   s1->ne[2] % s0->ne[2] == 0 && s1->ne[3] % s0->ne[3] == 0 &&
                   ggml_get_op_params_i32(op, 1) != GGML_HINT_SRC0_IS_HADAMARD;
        default:
            return false;
    }
}

static const struct ggml_backend_device_i omega_dev_i = {
    .get_name = dev_name,
    .get_description = dev_desc,
    .get_memory = dev_memory,
    .get_type = dev_type,
    .get_props = dev_props,
    .init_backend = dev_init,
    .get_buffer_type = dev_buft,
    .buffer_from_host_ptr = dev_from_ptr,
    .supports_op = dev_supports_op,
    .supports_buft = dev_supports_buft,
};

// OMEGA_GGML_DEVICES picks the devices: unset or "host" the host device only, "gb10" the GB10 device only,
// "host,gb10" both (GB10 needs a build with OMEGA_GGML_GB10=1; otherwise "gb10" registers nothing).
static struct ggml_backend_device omega_devs[2];
static size_t omega_ndev;
static void devs_init(ggml_backend_reg_t r) {
    static bool done;
    if (done) return;
    done = true;
    const char *e = getenv("OMEGA_GGML_DEVICES");
    const bool host = !e || strstr(e, "host") != NULL;
#ifdef OMEGA_GGML_GB10
    const bool gb10 = e && strstr(e, "gb10") != NULL;
#else
    const bool gb10 = false;
#endif
    if (host) omega_devs[omega_ndev++] = (struct ggml_backend_device) { .iface = omega_dev_i, .reg = r, .context = NULL };
    if (gb10) omega_devs[omega_ndev++] = (struct ggml_backend_device) { .iface = omega_dev_i, .reg = r, .context = &gb10_tag };
}
static const char *reg_name(ggml_backend_reg_t r) { (void) r; return "Omega"; }
static size_t reg_count(ggml_backend_reg_t r) { devs_init(r); return omega_ndev; }
static ggml_backend_dev_t reg_dev(ggml_backend_reg_t r, size_t i) {
    devs_init(r);
    GGML_ASSERT(i < omega_ndev);
    return &omega_devs[i];
}
static void *reg_proc(ggml_backend_reg_t r, const char *name) {
    (void) r;
    if (strcmp(name, "ggml_backend_set_n_threads") == 0) return (void *) omega_set_n_threads;
    return NULL;
}

static const struct ggml_backend_reg_i omega_reg_i = {
    .get_name = reg_name, .get_device_count = reg_count, .get_device = reg_dev, .get_proc_address = reg_proc,
};

static ggml_backend_reg_t omega_reg(void) {
    static struct ggml_backend_reg reg = { .api_version = GGML_BACKEND_API_VERSION, .iface = omega_reg_i, .context = NULL };
    return &reg;
}

