// A non-zero status (trap, refused argument, runtime failure) is never ignored.
#define OK(call)                                                                       \
    do {                                                                               \
        uint32_t st_ = (call);                                                         \
        if (st_ != 0) GGML_ABORT("ggml-omega: %s returned Omega status %u", #call, st_); \
    } while (0)

#define TILE 32

static int32_t ggml_get_op_params_i32(const struct ggml_tensor *t, uint32_t i) { int32_t v; memcpy(&v, (const char *) t->op_params + 4 * i, 4); return v; }
static float ggml_get_op_params_f32(const struct ggml_tensor *t, uint32_t i) { float v; memcpy(&v, (const char *) t->op_params + 4 * i, 4); return v; }

static uint64_t bits_f32(float f) { uint32_t u; memcpy(&u, &f, 4); return u; }
static float f32_bits(uint64_t v) { uint32_t u = (uint32_t) v; float f; memcpy(&f, &u, 4); return f; }

static char *at(const struct ggml_tensor *t, int64_t i1, int64_t i2, int64_t i3) {
    return (char *) t->data + i1 * t->nb[1] + i2 * t->nb[2] + i3 * t->nb[3];
}

// --- row kernels: tiles of 32 lanes, then single lanes; outputs staged through t[] -------------

static void row_bin(uint64_t op, const float *a, const float *b, float *d, int64_t n) {
    float t[TILE]; uint64_t r; int64_t i = 0;
    for (; i + TILE <= n; i += TILE) { OK(omega_bin_32(&r, op, a + i, TILE, b + i, TILE, t, TILE)); memcpy(d + i, t, sizeof t); }
    for (; i < n; i++) { OK(omega_bin_1(&r, op, a + i, 1, b + i, 1, t, 1)); d[i] = t[0]; }
}

static void row_scl(const float *x, float *d, int64_t n, uint64_t s, uint64_t b) {
    float t[TILE]; uint64_t r; int64_t i = 0;
    for (; i + TILE <= n; i += TILE) { OK(omega_scl_32(&r, x + i, TILE, t, TILE, s, b)); memcpy(d + i, t, sizeof t); }
    for (; i < n; i++) { OK(omega_scl_1(&r, x + i, 1, t, 1, s, b)); d[i] = t[0]; }
}

// one row of src (f32, f16 or q8_0) to f32 or f16 at d
static void row_cvt(enum ggml_type st, const void *s, enum ggml_type dt, void *d, int64_t n) {
    uint64_t r; int64_t i = 0;
    if (st == GGML_TYPE_Q8_0) {
        float t[32];
        for (; i < n / 32; i++) { OK(omega_dq8r(&r, (const char *) s + 34 * i, 34, t, 32)); memcpy((float *) d + 32 * i, t, sizeof t); }
        return;
    }
    if (dt == GGML_TYPE_F32) {
        float t[TILE]; float *df = d;
        if (st == GGML_TYPE_F32) {
            const float *sf = s;
            for (; i + TILE <= n; i += TILE) { OK(omega_cpy_32(&r, sf + i, TILE, t, TILE)); memcpy(df + i, t, sizeof t); }
            for (; i < n; i++) { OK(omega_cpy_1(&r, sf + i, 1, t, 1)); df[i] = t[0]; }
        } else {
            const uint16_t *sh = s;
            for (; i + TILE <= n; i += TILE) { OK(omega_h2fv_32(&r, sh + i, TILE, t, TILE)); memcpy(df + i, t, sizeof t); }
            for (; i < n; i++) { OK(omega_h2fv_1(&r, sh + i, 1, t, 1)); df[i] = t[0]; }
        }
    } else {
        uint16_t t[TILE]; uint16_t *dh = d;
        if (st == GGML_TYPE_F32) {
            const float *sf = s;
            for (; i + TILE <= n; i += TILE) { OK(omega_f2hv_32(&r, sf + i, TILE, t, TILE)); memcpy(dh + i, t, sizeof t); }
            for (; i < n; i++) { OK(omega_f2hv_1(&r, sf + i, 1, t, 1)); dh[i] = t[0]; }
        } else {
            const uint16_t *sh = s;
            for (; i + TILE <= n; i += TILE) { OK(omega_cpyh_32(&r, sh + i, TILE, t, TILE)); memcpy(dh + i, t, sizeof t); }
            for (; i < n; i++) { OK(omega_cpyh_1(&r, sh + i, 1, t, 1)); dh[i] = t[0]; }
        }
    }
}

// dot of one weight row (f32, f16 or q8_0) with one f32 row of k elements
static float row_dot(enum ggml_type wt, const void *w, const float *x, int64_t k) {
    uint64_t acc = 0; int64_t i = 0;
    if (wt == GGML_TYPE_Q8_0) {
        const char *wb = w; const int64_t nb = k / 32;
        while (i < nb) {
            if (nb - i >= 8) { OK(omega_dq8_8(&acc, acc, wb + 34 * i, 272, x + 32 * i, 256, nb - i == 8)); i += 8; }
            else { OK(omega_dq8_1(&acc, acc, wb + 34 * i, 34, x + 32 * i, 32, nb - i == 1)); i += 1; }
        }
    } else if (wt == GGML_TYPE_F16) {
        const uint16_t *wh = w;
        while (i < k) {
            if (k - i >= 256) { OK(omega_dh16_256(&acc, acc, wh + i, 256, x + i, 256, k - i == 256)); i += 256; }
            else if (k - i >= 32) { OK(omega_dh16_32(&acc, acc, wh + i, 32, x + i, 32, k - i == 32)); i += 32; }
            else { OK(omega_dh16_1(&acc, acc, wh + i, 1, x + i, 1, k - i == 1)); i += 1; }
        }
    } else {
        const float *wf = w;
        while (i < k) {
            if (k - i >= 256) { OK(omega_df32_256(&acc, acc, wf + i, 256, x + i, 256, k - i == 256)); i += 256; }
            else if (k - i >= 32) { OK(omega_df32_32(&acc, acc, wf + i, 32, x + i, 32, k - i == 32)); i += 32; }
            else { OK(omega_df32_1(&acc, acc, wf + i, 1, x + i, 1, k - i == 1)); i += 1; }
        }
    }
    return f32_bits(acc);
}

// --- ops ------------------------------------------------------------------------------------------

static void op_bin(struct ggml_tensor *dst, uint64_t code) {
    const struct ggml_tensor *a = dst->src[0], *b = dst->src[1];
    for (int64_t i3 = 0; i3 < dst->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < dst->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < dst->ne[1]; i1++)
                row_bin(code, (const float *) at(a, i1, i2, i3),
                        (const float *) at(b, i1 % b->ne[1], i2 % b->ne[2], i3 % b->ne[3]),
                        (float *) at(dst, i1, i2, i3), dst->ne[0]);
}

static void op_rms_norm(struct ggml_tensor *dst) {
    const struct ggml_tensor *x = dst->src[0];
    const uint64_t eps = bits_f32(ggml_get_op_params_f32(dst, 0));
    const int64_t n = x->ne[0];
    for (int64_t i3 = 0; i3 < x->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < x->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < x->ne[1]; i1++) {
                const float *xr = (const float *) at(x, i1, i2, i3);
                uint64_t acc = 0, sc; int64_t i = 0;
                for (; i + TILE <= n; i += TILE) OK(omega_sq_32(&acc, acc, xr + i, TILE));
                for (; i < n; i++) OK(omega_sq_1(&acc, acc, xr + i, 1));
                OK(omega_rmsc(&sc, acc, (uint64_t) n, eps));
                row_scl(xr, (float *) at(dst, i1, i2, i3), n, sc, 0);
            }
}

static void op_scale(struct ggml_tensor *dst) {
    const struct ggml_tensor *x = dst->src[0];
    const uint64_t s = bits_f32(ggml_get_op_params_f32(dst, 0)), b = bits_f32(ggml_get_op_params_f32(dst, 1));
    for (int64_t i3 = 0; i3 < x->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < x->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < x->ne[1]; i1++)
                row_scl((const float *) at(x, i1, i2, i3), (float *) at(dst, i1, i2, i3), x->ne[0], s, b);
}

static void op_soft_max(struct ggml_tensor *dst) {
    const struct ggml_tensor *x = dst->src[0], *m = dst->src[1];
    const uint64_t sc = bits_f32(ggml_get_op_params_f32(dst, 0));
    const int64_t n = x->ne[0];
    float t[TILE]; uint64_t r;
    for (int64_t i3 = 0; i3 < x->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < x->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < x->ne[1]; i1++) {
                const float *xr = (const float *) at(x, i1, i2, i3);
                float *dr = (float *) at(dst, i1, i2, i3);
                int64_t i = 0;
                if (!m) {
                    row_scl(xr, dr, n, sc, 0);
                } else {
                    const char *mr = at(m, i1, i2 % m->ne[2], i3 % m->ne[3]);
                    if (m->type == GGML_TYPE_F32) {
                        const float *mf = (const float *) mr;
                        for (; i + TILE <= n; i += TILE) { OK(omega_smw_32(&r, xr + i, TILE, mf + i, TILE, t, TILE, sc)); memcpy(dr + i, t, sizeof t); }
                        for (; i < n; i++) { OK(omega_smw_1(&r, xr + i, 1, mf + i, 1, t, 1, sc)); dr[i] = t[0]; }
                    } else {
                        const uint16_t *mh = (const uint16_t *) mr;
                        for (; i + TILE <= n; i += TILE) { OK(omega_smwh_32(&r, xr + i, TILE, mh + i, TILE, t, TILE, sc)); memcpy(dr + i, t, sizeof t); }
                        for (; i < n; i++) { OK(omega_smwh_1(&r, xr + i, 1, mh + i, 1, t, 1, sc)); dr[i] = t[0]; }
                    }
                }
                uint64_t mx = bits_f32(-INFINITY), sum = 0, rs;
                for (i = 0; i + TILE <= n; i += TILE) OK(omega_vmax_32(&mx, mx, dr + i, TILE));
                for (; i < n; i++) OK(omega_vmax_1(&mx, mx, dr + i, 1));
                for (i = 0; i + TILE <= n; i += TILE) OK(omega_sexp_32(&sum, sum, dr + i, TILE, mx));
                for (; i < n; i++) OK(omega_sexp_1(&sum, sum, dr + i, 1, mx));
                OK(omega_rcp(&rs, sum));
                row_scl(dr, dr, n, rs, 0);
            }
}

static void op_rope(struct ggml_tensor *dst) {
    const struct ggml_tensor *x = dst->src[0], *p = dst->src[1];
    const int n_dims = ggml_get_op_params_i32(dst, 1), mode = ggml_get_op_params_i32(dst, 2);
    const int n_offs = ggml_get_op_params_i32(dst, 15);
    const uint64_t fs = bits_f32(ggml_get_op_params_f32(dst, 6)), af = bits_f32(ggml_get_op_params_f32(dst, 8));
    const uint64_t fa = fs | (af << 32);
    uint64_t ts;
    OK(omega_rtsc(&ts, bits_f32(ggml_get_op_params_f32(dst, 5)), (uint64_t) n_dims));
    const int64_t half = n_dims / 2, step = mode == GGML_ROPE_TYPE_NEOX ? half : 1;
    const int32_t *pos = (const int32_t *) p->data;
    for (int64_t i3 = 0; i3 < x->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < x->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < x->ne[1]; i1++) {
                const float *s = (const float *) at(x, i1, i2, i3);
                float *d = (float *) at(dst, i1, i2, i3);
                float tail[TILE];
                for (int64_t k = 0; k < half; k++) {
                    const int64_t c = n_offs + (mode == GGML_ROPE_TYPE_NEOX ? k : 2 * k);
                    const uint64_t xy = bits_f32(s[c]) | (bits_f32(s[c + step]) << 32);
                    uint64_t o;
                    OK(omega_rope(&o, xy, (uint32_t) pos[i2], (uint64_t) k, ts, fa));
                    const float o0 = f32_bits(o), o1 = f32_bits(o >> 32);
                    d[c] = o0; d[c + step] = o1;
                }
                // channels outside [n_offs, n_offs + n_dims) are copied (Omega cpy tiles)
                for (int64_t i0 = 0; i0 < x->ne[0];) {
                    if (i0 == n_offs) { i0 += n_dims; continue; }
                    const int64_t end = i0 < n_offs ? n_offs : x->ne[0];
                    for (; i0 < end; i0++) { uint64_t r; OK(omega_cpy_1(&r, s + i0, 1, tail, 1)); d[i0] = tail[0]; }
                }
            }
}

static void op_get_rows(struct ggml_tensor *dst) {
    const struct ggml_tensor *w = dst->src[0], *ix = dst->src[1];
    for (int64_t i12 = 0; i12 < ix->ne[2]; i12++)
        for (int64_t i11 = 0; i11 < ix->ne[1]; i11++)
            for (int64_t i10 = 0; i10 < ix->ne[0]; i10++) {
                const int64_t r = *(const int32_t *) ((const char *) ix->data + i10 * ix->nb[0] + i11 * ix->nb[1] + i12 * ix->nb[2]);
                GGML_ASSERT(r >= 0 && r < w->ne[1]);
                row_cvt(w->type, at(w, r, i11, i12), dst->type, at(dst, i10, i11, i12), w->ne[0]);
            }
}

static void op_set_rows(struct ggml_tensor *dst) {
    const struct ggml_tensor *s = dst->src[0], *ix = dst->src[1];
    for (int64_t i03 = 0; i03 < s->ne[3]; i03++)
        for (int64_t i02 = 0; i02 < s->ne[2]; i02++)
            for (int64_t i = 0; i < s->ne[1]; i++) {
                const char *ip = (const char *) ix->data + i * ix->nb[0] + (i02 % ix->ne[1]) * ix->nb[1] + (i03 % ix->ne[2]) * ix->nb[2];
                const int64_t r = ix->type == GGML_TYPE_I64 ? *(const int64_t *) ip : *(const int32_t *) ip;
                GGML_ASSERT(r >= 0 && r < dst->ne[1]);
                row_cvt(s->type, at(s, i, i02, i03), dst->type, at(dst, r, i02, i03), s->ne[0]);
            }
}

static void op_cpy(struct ggml_tensor *dst) {
    const struct ggml_tensor *s = dst->src[0];
    if (ggml_are_same_shape(s, dst)) {
        for (int64_t i3 = 0; i3 < s->ne[3]; i3++)
            for (int64_t i2 = 0; i2 < s->ne[2]; i2++)
                for (int64_t i1 = 0; i1 < s->ne[1]; i1++)
                    row_cvt(s->type, at(s, i1, i2, i3), dst->type, at(dst, i1, i2, i3), s->ne[0]);
    } else {  // both contiguous (checked in supports_op): one flat row
        row_cvt(s->type, s->data, dst->type, dst->data, ggml_nelements(s));
    }
}

static void op_swiglu(struct ggml_tensor *dst) {
    const struct ggml_tensor *a = dst->src[0], *b = dst->src[1];
    const int64_t nc = dst->ne[0];
    const int swapped = ggml_get_op_params_i32(dst, 1);
    float t[TILE]; uint64_t r;
    for (int64_t i3 = 0; i3 < dst->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < dst->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < dst->ne[1]; i1++) {
                const float *ap = (const float *) at(a, i1, i2, i3);
                const float *bp = b ? (const float *) at(b, i1, i2, i3) : ap;
                if (!b) { ap += swapped ? nc : 0; bp += swapped ? 0 : nc; }
                float *d = (float *) at(dst, i1, i2, i3);
                int64_t i = 0;
                for (; i + TILE <= nc; i += TILE) { OK(omega_swi_32(&r, ap + i, TILE, bp + i, TILE, t, TILE)); memcpy(d + i, t, sizeof t); }
                for (; i < nc; i++) { OK(omega_swi_1(&r, ap + i, 1, bp + i, 1, t, 1)); d[i] = t[0]; }
            }
}

static void op_silu(struct ggml_tensor *dst) {
    const struct ggml_tensor *a = dst->src[0];
    float t[TILE]; uint64_t r;
    for (int64_t i3 = 0; i3 < dst->ne[3]; i3++)
        for (int64_t i2 = 0; i2 < dst->ne[2]; i2++)
            for (int64_t i1 = 0; i1 < dst->ne[1]; i1++) {
                const float *ap = (const float *) at(a, i1, i2, i3);
                float *d = (float *) at(dst, i1, i2, i3);
                int64_t i = 0;
                for (; i + TILE <= dst->ne[0]; i += TILE) { OK(omega_silu_32(&r, ap + i, TILE, t, TILE)); memcpy(d + i, t, sizeof t); }
                for (; i < dst->ne[0]; i++) { OK(omega_silu_1(&r, ap + i, 1, t, 1)); d[i] = t[0]; }
            }
}

// MUL_MAT: dst[i01, col] = dot(src0 row i01, src1 col). Weight rows are split across threads.
struct mm_job { struct ggml_tensor *dst; int64_t r0, r1; };

static void *mm_run(void *arg) {
    const struct mm_job *j = arg;
    struct ggml_tensor *dst = j->dst;
    const struct ggml_tensor *w = dst->src[0], *x = dst->src[1];
    const int64_t r2 = x->ne[2] / w->ne[2], r3 = x->ne[3] / w->ne[3];
    for (int64_t i13 = 0; i13 < x->ne[3]; i13++)
        for (int64_t i12 = 0; i12 < x->ne[2]; i12++)
            for (int64_t i11 = 0; i11 < x->ne[1]; i11++) {
                const float *xc = (const float *) at(x, i11, i12, i13);
                char *dc = at(dst, i11, i12, i13);
                for (int64_t i01 = j->r0; i01 < j->r1; i01++) {
                    const float v = row_dot(w->type, at(w, i01, i12 / r2, i13 / r3), xc, w->ne[0]);
                    memcpy(dc + i01 * dst->nb[0], &v, 4);
                }
            }
    return NULL;
}

static void op_mul_mat(struct ggml_tensor *dst, int n_threads) {
    const int64_t rows = dst->src[0]->ne[1];
    int nt = n_threads < 1 ? 1 : n_threads > 64 ? 64 : n_threads;
    if (rows < 2 * nt) nt = 1;
    struct mm_job jobs[64]; pthread_t th[64];
    for (int t = 0; t < nt; t++) jobs[t] = (struct mm_job) { dst, rows * t / nt, rows * (t + 1) / nt };
    for (int t = 1; t < nt; t++) if (pthread_create(&th[t], NULL, mm_run, &jobs[t]) != 0) GGML_ABORT("ggml-omega: pthread_create");
    mm_run(&jobs[0]);
    for (int t = 1; t < nt; t++) pthread_join(th[t], NULL);
}

