// ggml-omega: a ggml backend (llama.cpp backend API v3) whose op arithmetic runs in seeded-Omega units.
//
// INTERIM HOST GLUE. This C file only registers the backend, decides which ops it takes, walks tensor
// strides, slices rows into fixed-length tiles, stages tiles through a scratch buffer and moves bits.
// Every arithmetic step, every type conversion (f16, q8_0, int32 positions) and every libm-style
// function (exp, log, pow, sin, cos, sqrt) is computed by the Omega units in kernels/*.om, called
// through the omega-bridge native ABI (docs/NATIVE-ABI.md). Its .om successor is the Omega native
// loadable-object ABI (aien-dev/omega-mv #636 / #637): once Omega can export the ggml backend
// tables itself, this file is replaced by a .om unit.
//
// Device type ACCEL with the CPU buffer type, as ggml-blas: weights stay in CPU buffers (no copies),
// llama.cpp places ACCEL backends ahead of CPU, and the scheduler leaves every op this backend does
// not claim in supports_op on the CPU backend.

#include "ggml-backend-impl.h"
#include "ggml.h"

#include <math.h>
#include <pthread.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

